#!/usr/bin/env python3
"""Generate the Android launcher icon from scripts/plume-icon.svg.

The source art is a 24x24 pixel grid (16-bit style) whose rows are runs of
<rect> elements. The launcher uses the vane only: the long bare quill reads as
a thin diagonal inside a circular mask, so it is cropped below y=15 and the
remaining mark is scaled to fill the adaptive-icon safe circle.

Writes:
  app/src/main/res/drawable/ic_launcher_plume_foreground.xml
  app/src/main/res/drawable/ic_launcher_plume_monochrome.xml
"""
import collections
import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "plume-icon.svg"
RES = ROOT / "app" / "src" / "main" / "res" / "drawable"

PLATE = "#141414"
CROP_BELOW_Y = 15          # drop the bare quill
SAFE_RADIUS = 33.0         # 66dp adaptive-icon safe circle, radius in 108dp units
CENTER = 54.0
# Vane shades become one recolourable layer; the stem stays separate for the
# welcome animation.
LAYER = {"#1A1A1A": "body", "#4D4D4D": "body", "#9E9E9E": "body",
         "#D6D6D6": "body", "#F5F5F5": "stem", "#3D3D3D": "stem"}


def read_runs():
    svg = SRC.read_text()
    rows = re.findall(
        r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)" fill="(#\w+)"/>', svg)
    groups = collections.OrderedDict()
    cells = []
    for x, y, w, h, fill in rows:
        x, y, w, h = int(x), int(y), int(w), int(h)
        if fill.upper() == PLATE or y >= CROP_BELOW_Y:
            continue
        groups.setdefault(fill, []).append((x, y, w, h))
        cells += [(x + i, y + j) for i in range(w) for j in range(h)]
    return groups, cells


def path_data(runs):
    return "".join(f"M{x},{y}h{w}v{h}h-{w}z" for x, y, w, h in runs)


def main():
    groups, cells = read_runs()
    xs = [c[0] for c in cells]
    ys = [c[1] for c in cells]
    cx = (min(xs) + max(xs) + 1) / 2
    cy = (min(ys) + max(ys) + 1) / 2
    radius = max(math.hypot(px + 0.5 - cx, py + 0.5 - cy) for px, py in cells)
    scale = SAFE_RADIUS / radius
    tx, ty = CENTER - scale * cx, CENTER - scale * cy

    head = (
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        'android:width="108dp" android:height="108dp" '
        'android:viewportWidth="108" android:viewportHeight="108">\n'
        "    <!-- Generated by scripts/plume-icon-android.py from scripts/plume-icon.svg. -->\n"
        f'    <group android:scaleX="{scale:.4f}" android:scaleY="{scale:.4f}" '
        f'android:translateX="{tx:.4f}" android:translateY="{ty:.4f}">\n'
    )
    tail = "    </group>\n</vector>\n"

    RES.joinpath("ic_launcher_plume_foreground.xml").write_text(
        head + "\n".join(
            f'        <path android:name="{LAYER.get(f, "body")}" '
            f'android:fillColor="{f}" android:pathData="{path_data(runs)}"/>'
            for f, runs in groups.items()) + "\n" + tail)

    RES.joinpath("ic_launcher_plume_monochrome.xml").write_text(
        head + "".join(
            '        <path android:fillColor="#FFFFFF" '
            f'android:pathData="{path_data(runs)}"/>\n'
            for runs in groups.values()) + tail)

    print(f"scale {scale:.4f} translate {tx:.4f},{ty:.4f}")


if __name__ == "__main__":
    main()
