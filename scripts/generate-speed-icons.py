#!/usr/bin/env python3
"""Generate notification speed outlines: python generate-speed-icons.py Roboto.ttf.

Requires fonttools. Source: google/fonts ofl/roboto/Roboto[wdth,wght].ttf (OFL).
Use the same font size, weight and baseline for every label; never stretch glyphs.
"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

font = TTFont(sys.argv[1])
if 'fvar' in font:
    font = instantiateVariableFont(font, {'wght': 600, 'wdth': 100}, inplace=False)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
labels = {'075': '.75x', '1': '1x', '125': '1.25x', '15': '1.5x',
          '175': '1.75x', '2': '2x', '25': '2.5x', '3': '3x'}
# All variants share a size fitted to the widest label, leaving a 1dp inset.
widths = {key: sum(glyphs[cmap[ord(c)]].width for c in text) for key, text in labels.items()}
scale = 22 / max(widths.values())
height = font['OS/2'].sCapHeight * scale
baseline = (24 + height) / 2
root = Path(__file__).resolve().parent.parent / 'app/src/main/res/drawable'
for key, text in labels.items():
    pen = SVGPathPen(glyphs, ntos=lambda value: f'{value:.3f}'.rstrip('0').rstrip('.'))
    x = (24 - widths[key] * scale) / 2
    for c in text:
        glyph = glyphs[cmap[ord(c)]]
        glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += glyph.width * scale
    (root / f'audio_speed_{key}.xml').write_text(
        '<!-- Roboto SemiBold outlines, SIL OFL; generated by scripts/generate-speed-icons.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{pen.getCommands()}" />\n</vector>\n')
